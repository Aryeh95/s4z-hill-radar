// Generates pages/src/video-roads.mjs from Zwift's video route data (Zwift Plus video routes,
// course 18), so Hill Radar can show their climbs before Sauce has their roads.
//
// Usage: node scripts/video-roads.mjs [source]
//   source: base URL (default https://loveturtle.zwift.com/1.0.1) or a local folder with the
//   same layout (watopian/watopian.manifest.json and each file at its manifest key).

import fs from 'node:fs';
import path from 'node:path';

const source = process.argv[2] || 'https://loveturtle.zwift.com/1.0.1';
const out = path.join(path.dirname(new URL(import.meta.url).pathname), '../pages/src/video-roads.mjs');

async function get(key) {
    if (/^https?:/.test(source)) {
        const res = await fetch(`${source}/${key}`);
        if (!res.ok) {
            throw new Error(`${key}: HTTP ${res.status}`);
        }
        return await res.text();
    }
    return fs.readFileSync(path.join(source, key), 'utf8');
}

const attr = (s, k) => {
    const m = s.match(new RegExp(`\\b${k}="([^"]*)"`));
    return m ? m[1] : null;
};

// Road percent -> distance, like Sauce: road time spans the control points except the first and last.
function distanceAtRoadPercent(dists, p) {
    const idx = p * (dists.length - 3) + 1;
    const i = Math.min(dists.length - 2, Math.max(0, Math.floor(idx)));
    return dists[i] + (dists[i + 1] - dists[i]) * Math.min(1, Math.max(0, idx - i));
}

// Absolute values in decimetres, delta-encoded: "first,delta,delta,..."
function encode(values) {
    const dm = values.map(x => Math.round(x * 10));
    return dm.map((x, i) => i ? x - dm[i - 1] : x).join(',');
}

const manifest = JSON.parse(await get('watopian/watopian.manifest.json'));
const roads = [];
for (const collection of manifest.collections) {
    for (const ride of collection.rides) {
        const xml = await get(ride.road.key);
        const nodes = [...xml.matchAll(/<ent type="ENTITY_TYPE_ROADNODE"([^>]*)\/>/g)].map(m => {
            const pos = attr(m[1], 'm_pos').replace(/[{}]/g, '').split(',').map(Number);
            return {distance: Number(attr(m[1], 'm_videoDist')) / 100, elevation: pos[1] / 100};
        });
        if (nodes.length < 4 || nodes.some(n => !Number.isFinite(n.distance) || !Number.isFinite(n.elevation))) {
            console.warn(`Skipping ${ride.pretty_name}: no usable road nodes`);
            continue;
        }
        const dists = nodes.map(n => n.distance);
        const segments = [];
        if (ride.timed_path_segments) {
            const sx = await get(ride.timed_path_segments.key);
            for (const m of sx.matchAll(/<PathSegment\b[^>]*>([\s\S]*?)<\/PathSegment>/g)) {
                const parts = [...m[1].matchAll(/<PathPart\b([^>]*)\/>/g)]
                    .filter(p => Number(attr(p[1], 'roadid')) === ride.road_id);
                if (parts.length) {
                    const start = distanceAtRoadPercent(dists, Number(attr(parts[0][1], 'start')));
                    const end = distanceAtRoadPercent(dists, Number(attr(parts.at(-1)[1], 'end')));
                    if (end > start) {
                        segments.push([Math.round(start * 10) / 10, Math.round(end * 10) / 10]);
                    }
                }
            }
        }
        roads.push({id: ride.road_id, name: ride.pretty_name, segments, nodes});
        console.error(`${ride.pretty_name}: ${nodes.length} nodes, ${(dists.at(-1) / 1000).toFixed(2)} km, ` +
                      `${segments.length} segment(s)`);
    }
}
roads.sort((a, b) => a.id - b.id);

const lines = roads.map(r => `    ${r.id}: {
        name: ${JSON.stringify(r.name)},
        segments: ${JSON.stringify(r.segments)},
        distances: "${encode(r.nodes.map(n => n.distance))}",
        elevations: "${encode(r.nodes.map(n => n.elevation))}",
    },`);
fs.writeFileSync(out, `// Zwift video routes (Zwift Plus, course 18): one road each. Generated by
// scripts/video-roads.mjs from Zwift's video route data; do not edit by hand.
// ${roads.length} roads. Per road: name, timed segments [start, end] (m), and the road's control
// points: distance along the road and elevation, in decimetres, delta-encoded.

export const videoCourseId = 18;

export const videoRoads = {
${lines.join('\n')}
};
`);
console.error(`Wrote ${out}: ${roads.length} roads, ${(fs.statSync(out).size / 1024).toFixed(0)} KB`);
